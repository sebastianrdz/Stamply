/**
 * Serialize a rendered icon `<svg>` into a standalone SVG file (the stamp-icon
 * upload kind only accepts SVG). Sets xmlns and a fixed size so the wallet
 * rasterizer (resvg) can render it outside the page.
 */
export function svgFileFrom(svg: SVGElement, name = "icon"): File {
  const clone = svg.cloneNode(true) as SVGElement;
  clone.setAttribute("xmlns", "http://www.w3.org/2000/svg");
  clone.setAttribute("width", "256");
  clone.setAttribute("height", "256");
  return new File(
    [new XMLSerializer().serializeToString(clone)],
    `${name}.svg`,
    {
      type: "image/svg+xml",
    },
  );
}
